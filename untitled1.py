# BCBA QUICK-SWAP SCHEDULE OPTIMIZER (TEST SCRIPT)
# ==========================================

import math

# 1. SETUP: Mock Client Roster with mock locations (x, y coordinates) and auth hours
clients = [
    {
        "name": "Client A (Liam)",
        "location": (2, 3),          # 2 miles East, 3 miles North
        "remaining_auth_hours": 6,
        "session_type": "Direct 97155",
        "flexible_available": True
    },
    {
        "name": "Client B (Sophia)",
        "location": (8, 9),          # 8 miles East, 9 miles North
        "remaining_auth_hours": 10,
        "session_type": "Parent Training 97156",
        "flexible_available": True
    },
    {
        "name": "Client C (Noah)",
        "location": (3, 2),          # Very close to Client A
        "remaining_auth_hours": 4,
        "session_type": "Direct 97155",
        "flexible_available": True
    },
    {
        "name": "Client D (Emma)",
        "location": (1, 1),          # Close, but no remaining auth
        "remaining_auth_hours": 0,
        "session_type": "Direct 97155",
        "flexible_available": True
    }
]

# Function to estimate straight-line distance between two points
def calculate_distance(loc1, loc2):
    return math.sqrt((loc1[0] - loc2[0])**2 + (loc1[1] - loc2[1])**2)


# 2. SCENARIO: Cancellation Occurs
bcba_current_location = (2, 2)  # Where the BCBA is currently located
cancelled_time_slot = "Tuesday 10:00 AM - 12:00 PM (2 Hours)"

print("==================================================")
print(f"🚨 CANCELLATION NOTICE for {cancelled_time_slot}")
print(f"📍 BCBA Current Location Coordinates: {bcba_current_location}")
print("==================================================\n")


# 3. QUICK-SWAP ALGORITHM: Evaluate & Rank Options
eligible_options = []

for client in clients:
    # Rule 1: Must have remaining authorization hours
    if client["remaining_auth_hours"] <= 0:
        continue

    # Rule 2: Must be flexible/available
    if not client["flexible_available"]:
        continue

    # Calculate distance from BCBA's current location
    dist = calculate_distance(bcba_current_location, client["location"])

    # Add candidate to list
    eligible_options.append({
        "name": client["name"],
        "distance_miles": round(dist, 1),
        "auth_hours_left": client["remaining_auth_hours"],
        "type": client["session_type"]
    })

# Sort options by closest distance first
eligible_options.sort(key=lambda x: x["distance_miles"])


# 4. DISPLAY RESULTS
print("💡 TOP RECOMMENDED QUICK-SWAP OPTIONS:\n")

if not eligible_options:
    print("No eligible client swaps found with remaining authorization hours.")
else:
    for rank, option in enumerate(eligible_options, 1):
        print(f"Option #{rank}: {option['name']}")
        print(f"   • Distance: ~{option['distance_miles']} miles away")
        print(f"   • Service Type: {option['type']}")
        print(f"   • Remaining Auth Hours: {option['auth_hours_left']} hrs")
        print("--------------------------------------------------")